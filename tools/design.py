#!/usr/bin/env python3
"""Screen designs for the StatTrak display (128 x 32 pixels, each pixel is on or off).

A design file (designs/NAME.json) has one or more screens. Each screen is a list of elements:
text in a firmware font, rectangles, lines, firmware pictures and free pixels. A person makes it
with the Screen Designer (updater/designer/index.html). An AI tool can also write it by hand.
docs/DESIGNS.md has the file format.

    python tools/design.py check    designs/my.json      is the file correct?
    python tools/design.py render   designs/my.json      a PNG picture of each screen in out/
    python tools/design.py describe designs/my.json      the screens as text (elements + pixels)
    python tools/design.py code     designs/my.json      C draw code for a firmware view
    python tools/design.py assets                        update updater/designer/assets.js from
                                                         the firmware fonts (needs a build)

The pictures are exact: the fonts come from the firmware source, and a test compares each kind
of element with the real firmware draw functions.
"""

import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS_FILE = os.path.join(ROOT, "updater", "designer", "assets.js")
ASSETS_PREFIX = "window.STATTRAK_ASSETS = "
ASSETS_HEADER = ("// The StatTrak firmware fonts and pictures. Made from the firmware source by\n"
                 "// \"python tools/design.py assets\". Do not edit this file by hand.\n")

FORMAT_NAME = "stattrak-design"
FORMAT_VERSION = 1

WIDTH = 128
HEIGHT = 32

ELEMENT_TYPES = ("text", "rect", "line", "circle", "image", "pixels")
ALIGN_LETTERS = {"left": "L", "center": "C", "right": "R"}
ALIGN_C_NAMES = {"left": "GFX_ALIGN__LEFT", "center": "GFX_ALIGN__CENTER", "right": "GFX_ALIGN__RIGHT"}
MAX_SCALE = 8
MAX_BORDER = 4          # a cut-out border of 0 to 4 pixels around an element
MAX_CIRCLE_RADIUS = 127
COORD_LIMIT = 1000


class DesignError(Exception):
    """The design file is not correct."""


# --- Firmware fonts and pictures ---------------------------------------------------------------------

def load_assets(path=ASSETS_FILE):
    with open(path, "r", encoding="utf-8") as handle:
        text = handle.read()
    start = text.index(ASSETS_PREFIX) + len(ASSETS_PREFIX)
    end = text.rindex("}") + 1
    data = json.loads(text[start:end])
    data["font_by_name"] = {font["name"]: font for font in data["fonts"]}
    data["image_by_name"] = {image["name"]: image for image in data["images"]}
    return data


def find_gfx_tool():
    """The firmware draw code as a program. Built by tools/check.py."""
    candidates = [os.environ.get("STATTRAK_GFX_TOOL", "")]
    for name in ("gfx_tool", "gfx_tool.exe"):
        candidates.append(os.path.join(ROOT, "build-host", name))
    headless = os.environ.get("STATTRAK_HEADLESS", "")
    if headless:
        for name in ("gfx_tool", "gfx_tool.exe"):
            candidates.append(os.path.join(os.path.dirname(headless), name))
    for path in candidates:
        if path and os.path.isfile(path):
            return path
    return None


def write_assets(tool):
    result = subprocess.run([tool, "assets"], stdout=subprocess.PIPE, check=True)
    data = json.loads(result.stdout.decode("utf-8"))
    text = ASSETS_HEADER + ASSETS_PREFIX + json.dumps(data, separators=(",", ":"), sort_keys=True) + ";\n"
    with open(ASSETS_FILE, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    return text


# --- Read and check a design file --------------------------------------------------------------------

def _is_int(value):
    return isinstance(value, int) and not isinstance(value, bool)


def _number(element, key, where, problems, default=None, low=-COORD_LIMIT, high=COORD_LIMIT):
    value = element.get(key, default)
    if isinstance(value, float) and value.is_integer():
        value = int(value)      # 4.0 in a file is the whole number 4, as in the Screen Designer
    if not _is_int(value):
        problems.append("%s: \"%s\" must be a whole number." % (where, key))
        return 0
    if value < low or value > high:
        problems.append("%s: \"%s\" is %d. It must be from %d to %d." % (where, key, value, low, high))
        return 0
    return value


def _text(value, default):
    """A text value. A value of an other kind (number, null, list) is not used."""
    return value if isinstance(value, str) else default


def _color(element, where, problems):
    value = element.get("color", "white")
    if value not in ("white", "black"):
        problems.append("%s: \"color\" must be \"white\" (pixel on) or \"black\" (pixel off)." % where)
        return 1
    return 1 if value == "white" else 0


def text_width(font, text):
    """Width in pixels of a text at scale 1, as the firmware calculates it."""
    return sum(font["chars"][char]["w"] + font["space"] for char in text) - font["space"]


def normalize(design, assets):
    """Check a design. Return (clean design, problems, warnings). Problems make the file not usable."""
    problems = []
    warnings = []

    if not isinstance(design, dict):
        raise DesignError("The file must contain one JSON object.")
    if design.get("format") != FORMAT_NAME:
        problems.append("\"format\" must be \"%s\"." % FORMAT_NAME)
    if design.get("version") != FORMAT_VERSION or isinstance(design.get("version"), bool):
        problems.append("\"version\" must be %d." % FORMAT_VERSION)

    screens = design.get("screens")
    if not isinstance(screens, list) or not screens:
        problems.append("\"screens\" must be a list with one screen or more.")
        screens = []

    clean = {"format": FORMAT_NAME, "version": FORMAT_VERSION, "name": _text(design.get("name"), "Design"),
             "screens": []}
    used_ids = set()

    for index, screen in enumerate(screens):
        label = "Screen %d" % (index + 1)
        if not isinstance(screen, dict):
            problems.append("%s must be an object." % label)
            continue
        screen_id = _text(screen.get("id"), "screen%d" % (index + 1))
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]{0,30}", screen_id):
            problems.append("%s: \"id\" must start with a letter and have letters, digits and _ only "
                            "(31 characters at most). It is: %r" % (label, screen_id))
        if screen_id in used_ids:
            problems.append("%s: the id %r is used two times." % (label, screen_id))
        used_ids.add(screen_id)

        elements = screen.get("elements", [])
        if not isinstance(elements, list):
            problems.append("%s: \"elements\" must be a list." % label)
            elements = []

        clean_screen = {"id": screen_id, "name": _text(screen.get("name"), screen_id),
                        "note": _text(screen.get("note"), ""), "elements": []}

        for number, element in enumerate(elements, 1):
            where = "%s, element %d" % (label, number)
            if not isinstance(element, dict) or element.get("type") not in ELEMENT_TYPES:
                problems.append("%s: \"type\" must be one of: %s." % (where, ", ".join(ELEMENT_TYPES)))
                continue
            kind = element["type"]
            where = "%s (%s)" % (where, kind)
            item = {"type": kind, "color": _color(element, where, problems), "note": _text(element.get("note"), ""),
                    "border": _number(element, "border", where, problems, 0, 0, MAX_BORDER)}

            if kind == "text":
                font_name = element.get("font", "5x7")
                font = assets["font_by_name"].get(font_name) if isinstance(font_name, str) else None
                text = element.get("text", "")
                if font is None:
                    problems.append("%s: the font %r does not exist. Fonts: %s."
                                    % (where, element.get("font"), ", ".join(assets["font_by_name"])))
                    continue
                if not isinstance(text, str) or text == "":
                    problems.append("%s: \"text\" must not be empty." % where)
                    continue
                bad = sorted(set(char for char in text if char not in font["chars"]))
                if bad:
                    problems.append("%s: the firmware fonts do not have these characters: %s. Use the "
                                    "characters from space to ~ only (no letters with marks, no line breaks)."
                                    % (where, " ".join(repr(char) for char in bad)))
                    continue
                item.update(x=_number(element, "x", where, problems, 0), y=_number(element, "y", where, problems, 0),
                            text=text, font=font["name"], align=element.get("align", "left"),
                            scale=_number(element, "scale", where, problems, 1, 1, MAX_SCALE),
                            gap=element.get("gap") is True, invert=element.get("invert") is True)
                if not isinstance(item["align"], str) or item["align"] not in ALIGN_LETTERS:
                    problems.append("%s: \"align\" must be left, center or right." % where)
                    item["align"] = "left"
                if item["invert"] and item["scale"] != 1:
                    problems.append("%s: \"invert\" works with scale 1 only." % where)
                if item["gap"] and item["scale"] < 2:
                    warnings.append("%s: \"gap\" has no effect at scale 1." % where)
                    item["gap"] = False
                if font["name"] == "numbers" and re.search(r"[^0-9-]", text):
                    warnings.append("%s: the font \"numbers\" has the digits and \"-\" only. The firmware draws "
                                    "a 0 for each other character." % where)
                if font["name"] in ("5x5", "3x5", "big") and re.search(r"[a-z]", text):
                    warnings.append("%s: the font \"%s\" has capital letters only. Small letters are drawn as "
                                    "capitals." % (where, font["name"]))

            elif kind == "rect":
                item.update(x=_number(element, "x", where, problems, 0), y=_number(element, "y", where, problems, 0),
                            w=_number(element, "w", where, problems, None, 1), h=_number(element, "h", where, problems, None, 1),
                            fill=element.get("fill") is True,
                            radius=_number(element, "radius", where, problems, 0, 0, COORD_LIMIT))
                if item["w"] and item["h"]:
                    largest = (min(item["w"], item["h"]) - 1) // 2
                    if item["radius"] > largest:
                        problems.append("%s: \"radius\" %d is too large for %d x %d pixels. The largest is %d."
                                        % (where, item["radius"], item["w"], item["h"], largest))

            elif kind == "line":
                for key in ("x1", "y1", "x2", "y2"):
                    item[key] = _number(element, key, where, problems)

            elif kind == "circle":
                item.update(x=_number(element, "x", where, problems, 0), y=_number(element, "y", where, problems, 0),
                            r=_number(element, "r", where, problems, None, 0, MAX_CIRCLE_RADIUS),
                            fill=element.get("fill") is True)

            elif kind == "image":
                image_name = element.get("name")
                image = assets["image_by_name"].get(image_name) if isinstance(image_name, str) else None
                if image is None:
                    problems.append("%s: the picture %r does not exist. Pictures: %s."
                                    % (where, element.get("name"), ", ".join(assets["image_by_name"])))
                    continue
                item.update(name=image["name"], x=_number(element, "x", where, problems, 0),
                            y=_number(element, "y", where, problems, 0))

            elif kind == "pixels":
                rows = element.get("rows")
                if (not isinstance(rows, list) or not rows or len(rows) > HEIGHT
                        or any(not isinstance(row, str) or not re.fullmatch(r"[#.]+", row) for row in rows)
                        or len(set(len(row) for row in rows)) != 1 or len(rows[0]) > WIDTH):
                    problems.append("%s: \"rows\" must be 1 to %d lines of the same length (%d at most), with "
                                    "# for a pixel that is drawn and . for a pixel that is not."
                                    % (where, HEIGHT, WIDTH))
                    continue
                item.update(x=_number(element, "x", where, problems, 0), y=_number(element, "y", where, problems, 0),
                            rows=list(rows))

            clean_screen["elements"].append(item)

        clean["screens"].append(clean_screen)

    return clean, problems, warnings


def load_design(path, assets):
    try:
        with open(path, "r", encoding="utf-8") as handle:
            design = json.load(handle)
    except (OSError, ValueError) as error:
        raise DesignError("Cannot read %s: %s" % (path, error))
    clean, problems, warnings = normalize(design, assets)
    if problems:
        raise DesignError("%s is not correct:\n  - %s" % (path, "\n  - ".join(problems)))
    return clean, warnings


# --- Draw commands -----------------------------------------------------------------------------------
#
# One element becomes one draw command. A command is a tuple. The same list is used three times:
#   * draw_frame() draws it in Python (the picture that a person sees),
#   * tool_lines() gives it to the real firmware draw functions (the tests compare the result),
#   * c_code() writes it as C code for a firmware view.

def pixels_to_bitmap(rows):
    """Rows of # and . to the firmware picture format: one byte per column, for each band of 8 rows."""
    width = len(rows[0])
    height = len(rows)
    data = bytearray(width * ((height + 7) // 8))
    for y, row in enumerate(rows):
        for x, char in enumerate(row):
            if char == "#":
                data[(y // 8) * width + x] |= 1 << (y % 8)
    return bytes(data)


def element_commands(element, color=None):
    """The draw commands of one element (without its cut-out border). color: an other color."""
    commands = []
    kind = element["type"]
    if color is None:
        color = element["color"]
    if kind == "text":
        if element["scale"] == 1:
            commands.append(("text", element["font"], element["x"], element["y"], element["align"], color,
                             1 if element["invert"] else 0, element["text"]))
        else:
            commands.append(("scaled", element["font"], element["x"], element["y"], element["align"], color,
                             element["scale"], 1 if element["gap"] else 0, element["text"]))
    elif kind == "rect":
        x, y, w, h, radius = element["x"], element["y"], element["w"], element["h"], element["radius"]
        if element["fill"] or w == 1 or h == 1:
            if radius == 0:
                commands.append(("fill", x, y, w, h, color))
            else:
                commands.append(("frrect", x, y, w, h, radius, color))
        else:
            commands.append(("rrect", x, y, w, h, radius, color))
    elif kind == "line":
        commands.append(("line", element["x1"], element["y1"], element["x2"], element["y2"], color))
    elif kind == "image":
        commands.append(("image", element["name"], element["x"], element["y"], color))
    elif kind == "pixels":
        commands.append(("bitmap", element["x"], element["y"], len(element["rows"][0]), len(element["rows"]),
                         color, pixels_to_bitmap(element["rows"])))
    elif kind == "circle":
        commands.append(("fcircle" if element["fill"] else "circle", element["x"], element["y"], element["r"], color))
    return commands


# The places of the x and y values in each command (for a shifted copy: the cut-out border)
_X_AT = {"text": (2,), "scaled": (2,), "fill": (1,), "rrect": (1,), "frrect": (1,), "line": (1, 3),
         "image": (2,), "bitmap": (1,), "circle": (1,), "fcircle": (1,)}
_Y_AT = {"text": (3,), "scaled": (3,), "fill": (2,), "rrect": (2,), "frrect": (2,), "line": (2, 4),
         "image": (3,), "bitmap": (2,), "circle": (2,), "fcircle": (2,)}


def shift_command(command, dx, dy):
    parts = list(command)
    for i in _X_AT[command[0]]:
        parts[i] += dx
    for i in _Y_AT[command[0]]:
        parts[i] += dy
    return tuple(parts)


def border_parts(element, assets):
    """The cut-out border of an element: ("box", fill command) for an inverted text (the white box
    grows), else ("spread", N, commands in black): each command is drawn black at every place from
    -N to +N pixels around it. That switches off all pixels up to N pixels from the element."""
    n = element["border"]
    if element["type"] == "text" and element["invert"]:
        font = assets["font_by_name"][element["font"]]
        width = text_width(font, element["text"])
        x = element["x"]
        if element["align"] == "center":
            x -= width // 2
        elif element["align"] == "right":
            x -= width
        return ("box", ("fill", x - 1 - n, element["y"] - 1 - n, width + 2 + 2 * n, font["height"] + 2 + 2 * n, 0))
    return ("spread", n, element_commands(element, 0))


_ASSETS = []


def _assets():
    if not _ASSETS:
        _ASSETS.append(load_assets())
    return _ASSETS[0]


def screen_commands(screen, assets=None):
    """All draw commands of a screen. A cut-out border becomes shifted black copies of its element."""
    commands = []
    for element in screen["elements"]:
        if element.get("border"):
            part = border_parts(element, assets or _assets())
            if part[0] == "box":
                commands.append(part[1])
            else:
                n = part[1]
                for dy in range(-n, n + 1):
                    for dx in range(-n, n + 1):
                        commands.extend(shift_command(c, dx, dy) for c in part[2])
        commands.extend(element_commands(element))
    return commands


def tool_lines(commands):
    """The commands in the text format of sim/tools/gfx_tool.c."""
    lines = ["clear"]
    for command in commands:
        name = command[0]
        if name == "text":
            _, font, x, y, align, color, invert, text = command
            lines.append("text %s %d %d %s %d %d %s" % (font, x, y, ALIGN_LETTERS[align], color, invert, text))
        elif name == "scaled":
            _, font, x, y, align, color, scale, gap, text = command
            lines.append("scaled %s %d %d %s %d %d %d %s" % (font, x, y, ALIGN_LETTERS[align], color, scale, gap, text))
        elif name == "bitmap":
            _, x, y, w, h, color, data = command
            lines.append("bitmap %d %d %d %d %d %s" % (x, y, w, h, color, data.hex()))
        else:
            lines.append(" ".join(str(part) for part in command))
    lines.append("frame")
    return lines


# --- Draw in Python ----------------------------------------------------------------------------------

class Frame:
    """The display. The draw functions do the same as components/gfx/gfx.c, pixel for pixel."""

    def __init__(self, assets):
        self.assets = assets
        self.pixels = [[0] * WIDTH for _ in range(HEIGHT)]

    def pixel(self, x, y, color):
        if 0 <= x < WIDTH and 0 <= y < HEIGHT:
            self.pixels[y][x] = color

    def invert(self, x0, y0, x1, y1):
        for y in range(max(y0, 0), min(y1, HEIGHT)):
            for x in range(max(x0, 0), min(x1, WIDTH)):
                self.pixels[y][x] ^= 1

    def fill(self, x, y, w, h, color):
        for ix in range(x, x + w):
            for iy in range(y, y + h):
                self.pixel(ix, iy, color)

    def line(self, x0, y0, x1, y1, color):
        # The same steps as Gfx_drawLine()
        steep = abs(y1 - y0) > abs(x1 - x0)
        if steep:
            x0, y0, x1, y1 = y0, x0, y1, x1
        if x0 > x1:
            x0, x1, y0, y1 = x1, x0, y1, y0
        dx = x1 - x0
        dy = abs(y1 - y0)
        err = int(dx / 2)
        ystep = 1 if y0 < y1 else -1
        while x0 <= x1:
            if steep:
                self.pixel(y0, x0, color)
            else:
                self.pixel(x0, y0, color)
            err -= dy
            if err < 0:
                y0 += ystep
                err += dx
            x0 += 1

    def hline(self, x, y, width, color):
        self.line(x, y, x + width - 1, y, color)

    def vline(self, x, y, height, color):
        self.line(x, y, x, y + height - 1, color)

    def _corner_steps(self, radius):
        f = 1 - radius
        ddf_x = 1
        ddf_y = -2 * radius
        x = 0
        y = radius
        while x < y:
            if f >= 0:
                y -= 1
                ddf_y += 2
                f += ddf_y
            x += 1
            ddf_x += 2
            f += ddf_x
            yield x, y

    def round_rect(self, x, y, w, h, r, color):
        # The same steps as Gfx_drawRoundRect()
        self.hline(x + r, y, w - 2 * r, color)
        self.hline(x + r, y + h - 1, w - 2 * r, color)
        self.vline(x, y + r, h - 2 * r, color)
        self.vline(x + w - 1, y + r, h - 2 * r, color)
        corners = ((x + r, y + r, -1, -1), (x + w - r - 1, y + r, 1, -1),
                   (x + w - r - 1, y + h - r - 1, 1, 1), (x + r, y + h - r - 1, -1, 1))
        for cx, cy, sx, sy in corners:
            for px, py in self._corner_steps(r):
                self.pixel(cx + sx * px, cy + sy * py, color)
                self.pixel(cx + sx * py, cy + sy * px, color)

    def fill_round_rect(self, x, y, w, h, r, color):
        # The same steps as Gfx_fillRoundRect()
        self.fill(x + r, y, w - 2 * r, h, color)
        delta = h - 2 * r - 1
        for cx, sign in ((x + w - r - 1, 1), (x + r, -1)):
            cy = y + r
            for px, py in self._corner_steps(r):
                self.vline(cx + sign * px, cy - py, 2 * py + 1 + delta, color)
                self.vline(cx + sign * py, cy - px, 2 * px + 1 + delta, color)

    def circle(self, x0, y0, r, color):
        # The same steps as Gfx_drawCircle()
        for px, py in ((x0, y0 + r), (x0, y0 - r), (x0 + r, y0), (x0 - r, y0)):
            self.pixel(px, py, color)
        for x, y in self._corner_steps(r):
            for sx, sy in ((x, y), (-x, y), (x, -y), (-x, -y), (y, x), (-y, x), (y, -x), (-y, -x)):
                self.pixel(x0 + sx, y0 + sy, color)

    def fill_circle(self, x0, y0, r, color):
        # The same steps as Gfx_fillCircle()
        self.vline(x0, y0 - r, 2 * r + 1, color)
        for x, y in self._corner_steps(r):
            self.vline(x0 + x, y0 - y, 2 * y + 1, color)
            self.vline(x0 + y, y0 - x, 2 * x + 1, color)
            self.vline(x0 - x, y0 - y, 2 * y + 1, color)
            self.vline(x0 - y, y0 - x, 2 * x + 1, color)

    def rows(self, x, y, rows, color, scale=1, gap=0):
        size = scale - 1 if gap else scale
        for iy, row in enumerate(rows):
            for ix, char in enumerate(row):
                if char == "#":
                    if scale == 1:
                        self.pixel(x + ix, y + iy, color)
                    else:
                        self.fill(x + ix * scale, y + iy * scale, size, size, color)

    def text(self, font_name, x, y, align, color, invert, text, scale=1, gap=0):
        font = self.assets["font_by_name"][font_name]
        width = text_width(font, text)
        if align == "center":
            x -= (width // 2) * scale
        elif align == "right":
            x -= width * scale
        start = x
        for char in text:
            glyph = font["chars"][char]
            self.rows(x, y, glyph["rows"], color, scale, gap)
            x += (glyph["w"] + font["space"]) * scale
        if invert:
            self.invert(start - 1, y - 1, start + width + 1, y + font["height"] + 1)

    def draw(self, commands):
        for command in commands:
            name = command[0]
            if name == "text":
                _, font, x, y, align, color, invert, text = command
                self.text(font, x, y, align, color, invert, text)
            elif name == "scaled":
                _, font, x, y, align, color, scale, gap, text = command
                self.text(font, x, y, align, color, 0, text, scale, gap)
            elif name == "fill":
                self.fill(*command[1:])
            elif name == "rrect":
                self.round_rect(*command[1:])
            elif name == "frrect":
                self.fill_round_rect(*command[1:])
            elif name == "line":
                self.line(*command[1:])
            elif name == "circle":
                self.circle(*command[1:])
            elif name == "fcircle":
                self.fill_circle(*command[1:])
            elif name == "image":
                _, image_name, x, y, color = command
                self.rows(x, y, self.assets["image_by_name"][image_name]["rows"], color)
            elif name == "bitmap":
                _, x, y, w, h, color, data = command
                for iy in range(h):
                    for ix in range(w):
                        if data[(iy // 8) * w + ix] & (1 << (iy % 8)):
                            self.pixel(x + ix, y + iy, color)
        return self

    def lines(self):
        return ["".join("#" if value else "." for value in row) for row in self.pixels]


def draw_frame(screen, assets):
    """Return the screen as 32 strings of 128 characters. '#' is a pixel that is on."""
    return Frame(assets).draw(screen_commands(screen, assets)).lines()


def firmware_frame(screen, tool):
    """The same picture, drawn by the real firmware functions (needs the built gfx_tool)."""
    text = "\n".join(tool_lines(screen_commands(screen))) + "\n"
    result = subprocess.run([tool, "draw"], input=text.encode("ascii"), stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE)
    if result.returncode != 0:
        raise DesignError("gfx_tool failed: %s" % result.stderr.decode("utf-8", "replace").strip())
    return result.stdout.decode("ascii").split()


# --- Text for an AI tool -----------------------------------------------------------------------------

def _element_text(element, assets):
    kind = element["type"]
    color = "" if element["color"] else ", black (pixels off)"
    note = ("  [%s]" % element["note"]) if element["note"] else ""
    if element["border"]:
        color += ", cut-out border %d px (pixels up to %d px around it are off)" % (element["border"], element["border"])
    if kind == "circle":
        shape = "filled circle" if element["fill"] else "circle outline"
        return "%s center x=%d y=%d radius %d (%d x %d pixels)%s%s" % (
            shape, element["x"], element["y"], element["r"], 2 * element["r"] + 1, 2 * element["r"] + 1, color, note)
    if kind == "text":
        font = assets["font_by_name"][element["font"]]
        scale = element["scale"]
        width = text_width(font, element["text"]) * scale
        height = font["height"] * scale
        edge = {"left": "x is the left edge", "center": "x is the center", "right": "x is the right edge"}
        extra = ""
        if scale > 1:
            extra += ", scale %d%s" % (scale, " with a gap between the dots" if element["gap"] else "")
        if element["invert"]:
            extra += ", inverted (black text in a white box)"
        return ("text %s, font \"%s\"%s, x=%d y=%d (%s), %d x %d pixels%s%s"
                % (json.dumps(element["text"]), element["font"], extra, element["x"], element["y"],
                   edge[element["align"]], width, height, color, note))
    if kind == "rect":
        shape = "filled rectangle" if element["fill"] else "rectangle outline"
        radius = (", corner radius %d" % element["radius"]) if element["radius"] else ""
        return "%s x=%d y=%d w=%d h=%d%s%s%s" % (shape, element["x"], element["y"], element["w"], element["h"],
                                                radius, color, note)
    if kind == "line":
        return "line from x=%d y=%d to x=%d y=%d%s%s" % (element["x1"], element["y1"], element["x2"],
                                                        element["y2"], color, note)
    if kind == "image":
        image = assets["image_by_name"][element["name"]]
        return "firmware picture \"%s\" (%d x %d) at x=%d y=%d%s%s" % (element["name"], image["w"], image["h"],
                                                                      element["x"], element["y"], color, note)
    return "free pixels, %d x %d, at x=%d y=%d%s%s" % (len(element["rows"][0]), len(element["rows"]),
                                                       element["x"], element["y"], color, note)


def describe(design, assets, source=""):
    out = []
    count = len(design["screens"])
    out.append("StatTrak screen design \"%s\": %d screen%s." % (design["name"], count, "" if count == 1 else "s"))
    out.append("The display has %d x %d pixels. A pixel is on (white) or off (black). x goes to the right, "
               "y goes down, the top left pixel is x=0 y=0." % (WIDTH, HEIGHT))
    if source:
        out.append("Draw code for the firmware: python tools/design.py code %s" % source)
    for index, screen in enumerate(design["screens"], 1):
        out.append("")
        out.append("=== Screen %d of %d: \"%s\" (id: %s) ===" % (index, count, screen["name"], screen["id"]))
        out.append("What it does: %s" % (screen["note"] or "(no note)"))
        if screen["elements"]:
            out.append("Elements, in the order they are drawn (a later element is on top):")
            for number, element in enumerate(screen["elements"], 1):
                out.append("  %d. %s" % (number, _element_text(element, assets)))
        else:
            out.append("Elements: none (an empty screen).")
        out.append("Picture ('#' = pixel on):")
        out.extend(draw_frame(screen, assets))
    return "\n".join(out) + "\n"


# --- C code for a firmware view ----------------------------------------------------------------------

def _c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _one_line(text):
    """Free text for a // comment: no line breaks, and no backslash at the end (in C that
    joins the comment with the next line)."""
    return " ".join(text.split()).rstrip("\\ ")


def _c_name(screen_id):
    return screen_id[0].upper() + screen_id[1:]


def _c_call(command, assets, name, tables, dx, dy):
    """One C call of a draw command. dx, dy: text to add to the x and y values (" + dx")."""
    kind = command[0]
    xs = {i: "%d%s" % (command[i], dx) for i in _X_AT[kind]}
    xs.update({i: "%d%s" % (command[i], dy) for i in _Y_AT[kind]})
    v = [xs.get(i, command[i]) for i in range(len(command))]
    if kind == "text":
        _, font, x, y, align, color, invert, text = v
        return ("  Gfx_drawStringAligned(%s, %s, %s, &%s, %d, %d, %s, GFX_ROTATION__0);"
                % (x, y, _c_string(text), assets["font_by_name"][font]["symbol"], color, invert, ALIGN_C_NAMES[align]))
    if kind == "scaled":
        _, font, x, y, align, color, scale, gap, text = v
        return ("  Gfx_drawStringScaledAligned(%s, %s, %s, &%s, %d, %d, %d, %s);"
                % (x, y, _c_string(text), assets["font_by_name"][font]["symbol"], color, scale, gap, ALIGN_C_NAMES[align]))
    if kind in ("fill", "rrect", "frrect", "line", "circle", "fcircle"):
        function = {"fill": "Gfx_fillRect", "rrect": "Gfx_drawRoundRect", "frrect": "Gfx_fillRoundRect",
                    "line": "Gfx_drawLine", "circle": "Gfx_drawCircle", "fcircle": "Gfx_fillCircle"}[kind]
        return "  %s(%s);" % (function, ", ".join(str(part) for part in v[1:]))
    if kind == "image":
        _, image_name, x, y, color = v
        return ("  Gfx_drawBitmap(%s, %s, &%s, %d, GFX_ROTATION__0);"
                % (x, y, assets["image_by_name"][image_name]["symbol"], color))
    # bitmap: one table for each different picture of the screen
    _, x, y, w, h, color, data = v
    rows = ["  " + ", ".join("0x%02X" % byte for byte in data[start:start + 16]) + ","
            for start in range(0, len(data), 16)]
    body = "\n".join(rows)
    table = None
    for known, known_body, _size in tables:
        if known_body == body:
            table = known
    if table is None:
        table = "k%sPixels%d" % (name, len(tables) + 1)
        tables.append((table, body, "%d x %d" % (w, h)))
    return "  Gfx_drawBitmapRaw(%s, %s, %s, %d, %d, %d, GFX_ROTATION__0);" % (x, y, table, w, h, color)


def c_code(design, assets, source=""):
    out = []
    out.append("// Draw code for the screen design \"%s\"%s." % (_one_line(design["name"]),
                                                               (" (%s)" % source) if source else ""))
    out.append("// Made by tools/design.py. Put each function into the view that shows the screen, and call it")
    out.append("// from the draw function of the view. Replace the fixed texts with the real values.")
    out.append("// The files need: #include \"gfx.h\", \"font.h\", \"font_glyph.h\", \"img.h\"")

    for screen in design["screens"]:
        name = _c_name(screen["id"])
        body = []
        tables = []
        for element in screen["elements"]:
            comment = ("  // %s" % _one_line(element["note"])) if element["note"].strip() else ""
            if element["border"]:
                part = border_parts(element, assets)
                if part[0] == "box":
                    body.append(_c_call(part[1], assets, name, tables, "", "") +
                                "  // cut-out border of %d pixels" % element["border"])
                else:
                    n = part[1]
                    body.append("  for(int16_t dy = -%d; dy <= %d; dy++) {  // cut-out border of %d pixels"
                                % (n, n, n))
                    body.append("    for(int16_t dx = -%d; dx <= %d; dx++) {" % (n, n))
                    for command in part[2]:
                        body.append("    " + _c_call(command, assets, name, tables, " + dx", " + dy"))
                    body.append("    }")
                    body.append("  }")
            for command in element_commands(element):
                body.append(_c_call(command, assets, name, tables, "", "") + comment)

        out.append("")
        out.extend("// Free pixels of the screen \"%s\", %s\nstatic const uint8_t %s[] = {\n%s\n};"
                   % (_one_line(screen["name"]), size, table, body) for table, body, size in tables)
        if tables:
            out.append("")
        out.append("// Screen \"%s\"%s" % (_one_line(screen["name"]),
                                           (": " + _one_line(screen["note"])) if screen["note"].strip() else ""))
        out.append("static void _draw%s(void) {" % name)
        out.extend(body if body else ["  // An empty screen"])
        out.append("}")
    return "\n".join(out) + "\n"


# --- Command line ------------------------------------------------------------------------------------

def _png(path, frame, scale):
    sys.path.insert(0, os.path.join(ROOT, "tests"))
    from stattrak_sim import write_png
    write_png(path, frame, scale)


def main():
    parser = argparse.ArgumentParser(description="StatTrak screen designs", epilog="File format: docs/DESIGNS.md")
    sub = parser.add_subparsers(dest="action", required=True)
    for name, text in (("check", "check a design file"), ("render", "save a PNG picture of each screen"),
                       ("describe", "print the screens as text"), ("code", "print C draw code")):
        action = sub.add_parser(name, help=text)
        action.add_argument("file", help="design file, for example designs/my.json")
        if name == "render":
            action.add_argument("--out", default=os.path.join(ROOT, "out"), help="folder for the pictures (default: out/)")
            action.add_argument("--scale", type=int, default=4, help="size of one display pixel in the picture (default 4)")
        if name in ("describe", "code"):
            action.add_argument("--screen", help="only the screen with this id")
    sub.add_parser("assets", help="update updater/designer/assets.js from the firmware (needs a build)")
    args = parser.parse_args()

    if args.action == "assets":
        tool = find_gfx_tool()
        if tool is None:
            print("gfx_tool is not built. Run first: python tools/check.py --build-only", file=sys.stderr)
            return 2
        write_assets(tool)
        print("Wrote %s" % os.path.relpath(ASSETS_FILE, ROOT))
        return 0

    assets = load_assets()
    try:
        design, warnings = load_design(args.file, assets)
        if getattr(args, "screen", None):
            design["screens"] = [screen for screen in design["screens"] if screen["id"] == args.screen]
            if not design["screens"]:
                raise DesignError("There is no screen with the id %r." % args.screen)
    except DesignError as error:
        print(error, file=sys.stderr)
        return 1

    for warning in warnings:
        print("Note: %s" % warning, file=sys.stderr)

    shown = os.path.relpath(os.path.abspath(args.file), ROOT).replace(os.sep, "/")

    if args.action == "check":
        print("%s: OK (%d screen%s)" % (shown, len(design["screens"]), "" if len(design["screens"]) == 1 else "s"))
    elif args.action == "render":
        os.makedirs(args.out, exist_ok=True)
        base = os.path.splitext(os.path.basename(args.file))[0]
        for screen in design["screens"]:
            path = os.path.join(args.out, "%s_%s.png" % (base, screen["id"]))
            _png(path, draw_frame(screen, assets), max(1, args.scale))
            print(path)
    elif args.action == "describe":
        sys.stdout.write(describe(design, assets, shown))
    elif args.action == "code":
        sys.stdout.write(c_code(design, assets, shown))
    return 0


if __name__ == "__main__":
    sys.exit(main())
