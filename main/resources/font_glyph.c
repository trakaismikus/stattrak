uint8_t FontNightverbBig_charToIdx(char c)
{
  uint8_t c_idx;
  // uint8_t uc = (uint8_t)c;

  if(c >= ' ' && c <= '_')
    c_idx = c - ' ';
  else if(c >= 'a' && c <= 'z')
    c_idx = c - 'a' + ('A' - ' ');
  else
    c_idx = 0;

  return c_idx;
}

uint8_t FontNightverbLargeNumbers_charToIdx(char c)
{
  uint8_t c_idx = 0;

  if(c >= '0' && c <= '9')
    c_idx = c - '0';
  else if(c == '-')
    c_idx = 10;
  else
    c_idx = 0;

  return c_idx;
}

